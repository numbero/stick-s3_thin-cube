#!/usr/bin/env python3
"""Generate the approved 51px OTA completion badge as a native RGB565 asset.

Compute edge coverage offline so the device only draws horizontal color spans;
no framebuffer allocation or floating-point rasterization is needed at runtime.
"""
import math
from pathlib import Path


def distance(x, y, ax, ay, bx, by):
    vx, vy = bx - ax, by - ay
    t = max(0, min(1, ((x - ax) * vx + (y - ay) * vy) / (vx * vx + vy * vy)))
    return math.hypot(x - ax - t * vx, y - ay - t * vy)


def pixel(x, y):
    total = [0, 0, 0]
    for sy in range(8):
        for sx in range(8):
            px, py = x + (sx + .5) / 8 - .5, y + (sy + .5) / 8 - .5
            radius = math.hypot(px, py)
            rgb = (16, 31, 25) if radius <= 21.5 else (13, 13, 13)
            if abs(radius - 21.5) <= .95 or min(
                distance(px, py, -9, 0, -3, 6), distance(px, py, -3, 6, 10, -8)
            ) <= 1.65:
                rgb = (61, 220, 151)
            total = [a + b for a, b in zip(total, rgb)]
    r, g, b = (math.floor(v / 64 + .5) for v in total)
    return ((r & 248) << 8) | ((g & 252) << 3) | (b >> 3)


def main():
    values = [pixel(x, y) for y in range(-25, 26) for x in range(-25, 26)]
    lines = ["  " + ",".join(f"0x{v:04x}" for v in values[i:i + 12]) + ","
             for i in range(0, len(values), 12)]
    header = """#pragma once
#include <stdint.h>

// Generated by scripts/generate-ota-complete-badge.py. 8x8 coverage samples
// per native pixel; the circle and rounded check are blended before RGB565.
namespace OtaCompleteBadge {
constexpr int Width=51,Height=51;
static constexpr uint16_t Pixels[]={
""" + "\n".join(lines) + """
};
static_assert(sizeof(Pixels)/sizeof(Pixels[0])==Width*Height,"badge size");
template<class Canvas> void draw(Canvas& canvas,int cx,int cy){
  for(int row=0;row<Height;++row){
    for(int start=0;start<Width;){
      const uint16_t color=Pixels[row*Width+start];
      int end=start+1;
      while(end<Width&&Pixels[row*Width+end]==color)++end;
      canvas.fillRect(cx-Width/2+start,cy-Height/2+row,end-start,1,color);
      start=end;
    }
  }
}
}
"""
    path = Path(__file__).resolve().parents[1] / "firmware/src/ota_complete_badge.h"
    path.write_text(header)
    print(f"Generated {path.name}: {len(values) * 2} bytes of RGB565 pixels")


if __name__ == "__main__":
    main()
